"""Unit tests for Smoothing Wall Speed Along Z plugin."""

import os
import sys
import tempfile
import unittest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from smooth_z_wall_speed import (
    smooth_gcode_lines,
    smooth_gcode_file,
    parse_feedrate,
    set_feedrate_on_line,
    DEFAULT_CONFIG,
)


def generate_synthetic_gcode(
    num_layers=10,
    z_step=0.2,
    default_speed=12000.0,
    slow_layer_idx=5,
    slow_speed=3000.0,
    has_overhang=False,
    spiral_vase=False,
):
    """Generate minimal synthetic OrcaSlicer G-code for testing."""
    lines = [
        "; HEADER_START\n",
        f"; generated by OrcaSlicer\n",
    ]
    if spiral_vase:
        lines.append("; spiral_mode = 1\n")

    current_z = 0.2
    for l_idx in range(num_layers):
        lines.append(";LAYER_CHANGE\n")
        lines.append(f";Z:{current_z:.2f}\n")
        lines.append(f";HEIGHT:{z_step:.2f}\n")
        lines.append(f"G1 Z{current_z:.2f} F6000\n")

        # Inner wall
        lines.append(";TYPE:Inner wall\n")
        lines.append("G1 X10 Y10 E0.5 F15000\n")
        lines.append("G1 X20 Y10 E0.5\n")

        # Outer wall
        lines.append(";TYPE:Outer wall\n")
        speed = slow_speed if l_idx == slow_layer_idx else default_speed
        lines.append(f"G1 X10 Y10 E0.5 F{speed:.1f}\n")
        lines.append("G1 X20 Y10 E0.5\n")
        lines.append("G1 X20 Y20 E0.5\n")
        lines.append("G1 X10 Y20 E0.5\n")

        if has_overhang and l_idx == slow_layer_idx:
            lines.append(";TYPE:Overhang wall\n")
            lines.append(f"G1 X25 Y20 E0.3 F{slow_speed * 0.8:.1f}\n")

        # Infill
        lines.append(";TYPE:Sparse infill\n")
        lines.append("G1 X12 Y12 E0.4 F18000\n")

        current_z += z_step

    return lines


class TestSmoothZWallSpeed(unittest.TestCase):

    def test_parse_feedrate(self):
        self.assertEqual(parse_feedrate("G1 X100 Y50 E1.2 F12000"), 12000.0)
        self.assertEqual(parse_feedrate("G1 F6000.5"), 6000.5)
        self.assertIsNone(parse_feedrate("G1 X100 Y50 E1.2"))

    def test_set_feedrate_on_line(self):
        line = "G1 X100 Y50 E1.2 F12000 ; move"
        out = set_feedrate_on_line(line, 6000.0)
        self.assertIn("F6000.0", out)
        self.assertNotIn("F12000", out)
        self.assertIn("; move", out)

        line_no_f = "G1 X100 Y50 E1.2 ; comment\n"
        out_no_f = set_feedrate_on_line(line_no_f, 4500.0)
        self.assertIn("F4500.0", out_no_f)
        self.assertIn("; comment", out_no_f)

    def test_smoothing_abrupt_slowdown(self):
        # 10 layers, layer 5 is slow (3000 mm/min = 50 mm/s) vs 12000 mm/min (200 mm/s)
        lines = generate_synthetic_gcode(
            num_layers=10,
            z_step=0.2,
            default_speed=12000.0,
            slow_layer_idx=5,
            slow_speed=3000.0,
        )

        cfg = {
            "enabled": True,
            "max_speed_change_per_mm": 50.0, # 50 mm/s per mm Z -> 600 mm/min per 0.2mm layer
            "min_outer_wall_speed_mm_s": 10.0,
            "skip_first_layers": 1,
        }

        output_lines, stats = smooth_gcode_lines(lines, cfg)

        self.assertEqual(stats["total_layers"], 10)
        self.assertGreater(stats["smoothed_layers"], 0)
        self.assertGreater(stats["updated_moves"], 0)

        # Layers 4 and 6 adjacent to layer 5 should be smoothed down significantly below 12000
        # Check layer 4 speed in output:
        # Layer 5 is 3000. Layer 4 max allowed is ~ 3000 + 600 = 3600 mm/min.
        # Find outer wall speed in layer 4
        current_layer = -1
        in_outer = False
        layer_outer_speeds = {}
        for line in output_lines:
            if ";LAYER_CHANGE" in line:
                current_layer += 1
                in_outer = False
                continue
            if ";TYPE:Outer wall" in line:
                in_outer = True
                continue
            elif ";TYPE:" in line:
                in_outer = False
                continue
            if in_outer and "G1" in line:
                f_val = parse_feedrate(line)
                if f_val:
                    layer_outer_speeds[current_layer] = f_val

        # Layer 5 should remain at its safe slow speed
        self.assertAlmostEqual(layer_outer_speeds[5], 3000.0, delta=10.0)

        # Layer 4 and 6 must be pulled down significantly below original 12000
        self.assertLess(layer_outer_speeds[4], 6000.0)
        self.assertLess(layer_outer_speeds[6], 6000.0)

        # Layer 3 should also be smoothed down (e.g. ~ 4200)
        self.assertLess(layer_outer_speeds[3], 9000.0)

    def test_skip_first_layer(self):
        lines = generate_synthetic_gcode(
            num_layers=6,
            z_step=0.2,
            default_speed=12000.0,
            slow_layer_idx=1,
            slow_speed=3000.0,
        )
        cfg = {"skip_first_layers": 1}
        output_lines, stats = smooth_gcode_lines(lines, cfg)

        # Verify layer 0 speed was not changed
        current_layer = -1
        in_outer = False
        layer_0_speed = None
        for line in output_lines:
            if ";LAYER_CHANGE" in line:
                current_layer += 1
                continue
            if current_layer == 0 and ";TYPE:Outer wall" in line:
                in_outer = True
                continue
            if in_outer and current_layer == 0 and "G1" in line:
                f_val = parse_feedrate(line)
                if f_val:
                    layer_0_speed = f_val
                    break

        self.assertEqual(layer_0_speed, 12000.0)

    def test_spiral_vase_skipped(self):
        lines = generate_synthetic_gcode(num_layers=10, spiral_vase=True)
        _, stats = smooth_gcode_lines(lines)
        self.assertEqual(stats["skipped_reason"], "spiral_vase_mode")
        self.assertEqual(stats["updated_moves"], 0)

    def test_non_outer_walls_preserved(self):
        lines = generate_synthetic_gcode(num_layers=6, slow_layer_idx=3, slow_speed=2000.0)
        output_lines, _ = smooth_gcode_lines(lines)

        # Check that inner walls still print at 15000 and infill at 18000
        inner_wall_f = None
        infill_f = None
        for line in output_lines:
            if "E0.5 F15000" in line:
                inner_wall_f = 15000
            if "E0.4 F18000" in line:
                infill_f = 18000

        self.assertEqual(inner_wall_f, 15000)
        self.assertEqual(infill_f, 18000)

    def test_smooth_gcode_file_end_to_end(self):
        lines = generate_synthetic_gcode(num_layers=8, slow_layer_idx=4, slow_speed=3000.0)
        with tempfile.NamedTemporaryFile("w", delete=False, suffix=".gcode", encoding="utf-8") as f:
            f.writelines(lines)
            temp_in = f.name

        temp_out = temp_in + ".out.gcode"
        try:
            stats = smooth_gcode_file(temp_in, temp_out)
            self.assertEqual(stats["total_layers"], 8)
            self.assertGreater(stats["updated_moves"], 0)
            self.assertTrue(os.path.exists(temp_out))
            with open(temp_out, "r", encoding="utf-8") as f_out:
                out_content = f_out.read()
            self.assertIn(";TYPE:Outer wall", out_content)
        finally:
            if os.path.exists(temp_in):
                os.remove(temp_in)
            if os.path.exists(temp_out):
                os.remove(temp_out)


if __name__ == "__main__":
    unittest.main()
