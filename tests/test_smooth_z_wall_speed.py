def generate_synthetic_gcode(
    num_layers=10,
    z_step=0.2,
    default_speed=12000.0,
    slow_layer_idx=5,
    slow_speed=3000.0,
    has_overhang=False,
    spiral_vase=False,
):
    """Generate minimal synthetic OrcaSlicer G-code for testing."""
    lines = [
        "; HEADER_START\n",
        "; generated by OrcaSlicer\n",
    ]
    if spiral_vase:
        lines.append("; spiral_mode = 1\n")

    current_z = 0.2
    for l_idx in range(num_layers):
        lines.append(";LAYER_CHANGE\n")
        lines.append(f";Z:{current_z:.2f}\n")
        lines.append(f";HEIGHT:{z_step:.2f}\n")
        lines.append(f"G1 Z{current_z:.2f} F6000\n")

        # Inner wall
        lines.append(";TYPE:Inner wall\n")
        lines.append("G1 X10 Y10 E0.5 F15000\n")
        lines.append("G1 X20 Y10 E0.5\n")

        # Outer wall
        lines.append(";TYPE:Outer wall\n")
        speed = slow_speed if l_idx == slow_layer_idx else default_speed
        lines.append(f"G1 X10 Y10 E0.5 F{speed:.1f}\n")
        lines.append("G1 X20 Y10 E0.5\n")
        lines.append("G1 X20 Y20 E0.5\n")
        lines.append("G1 X10 Y20 E0.5\n")

        if has_overhang and l_idx == slow_layer_idx:
            lines.append(";TYPE:Overhang wall\n")
            lines.append(f"G1 X25 Y20 E0.3 F{slow_speed * 0.8:.1f}\n")

        # Infill
        lines.append(";TYPE:Sparse infill\n")
        lines.append("G1 X12 Y12 E0.4 F18000\n")

        current_z += z_step

    return lines


def generate_synthetic_bambu_gcode(
    num_layers=10,
    z_step=0.2,
    default_speed=30000.0,
    slow_layer_idx=5,
    slow_speed=3000.0,
):
    """Synthetic Bambu flavour G-code: '; layer num/...' and '; FEATURE:' comments."""
    lines = [
        "; HEADER_START\n",
        "; generated by Bambu Studio\n",
        "; spiral_mode = 0\n",
    ]

    for l_idx in range(num_layers):
        lines.append(f"; layer num/total_layer_count: {l_idx + 1}/{num_layers}\n")
        lines.append(f"G1 Z{(l_idx + 1) * z_step:.2f} F6000\n")

        lines.append("; FEATURE: Inner wall\n")
        lines.append("G1 X10 Y10 E0.5 F15000\n")

        lines.append("; FEATURE: Outer wall\n")
        speed = slow_speed if l_idx == slow_layer_idx else default_speed
        lines.append(f"G1 X10 Y10 E0.5 F{speed:.1f}\n")
        if l_idx == slow_layer_idx + 1:
            lines.append("G2 X30 Y30 I5 J0 E0.3 F30000.0\n")
        else:
            lines.append("G1 X20 Y10 E0.5\n")
        lines.append("G1 X20 Y20 E0.5\n")

        lines.append("; FEATURE: Overhang wall\n")
        lines.append(f"G1 X25 Y20 E0.3 F{speed * 0.8:.1f}\n")

        lines.append("; FEATURE: Sparse infill\n")
        lines.append("G1 X12 Y12 E0.4 F18000\n")

    return lines


def generate_inner_dip_gcode(num_layers=8, dip_layer_idx=4, dip_speed=3000.0):
    """Inner wall speed dips on one layer, outer wall stays constant."""
    lines = ["; HEADER_START\n"]
    for l_idx in range(num_layers):
        lines.append(";LAYER_CHANGE\n")
        lines.append(f";Z:{(l_idx + 1) * 0.2:.2f}\n")
        lines.append(";TYPE:Inner wall\n")
        inner_f = dip_speed if l_idx == dip_layer_idx else 15000.0
        lines.append(f"G1 X10 Y10 E0.5 F{inner_f:.1f}\n")
        lines.append(";TYPE:Outer wall\n")
        lines.append("G1 X10 Y10 E0.5 F12000\n")
    return lines


class TestSmoothZWallSpeed(unittest.TestCase):

    def test_parse_feedrate(self):
        self.assertEqual(parse_feedrate("G1 X100 Y50 E1.2 F12000"), 12000.0)
        self.assertEqual(parse_feedrate("G1 F6000.5"), 6000.5)
        self.assertIsNone(parse_feedrate("G1 X100 Y50 E1.2"))

    def test_set_feedrate_on_line(self):
        line = "G1 X100 Y50 E1.2 F12000 ; move"
        out = set_feedrate_on_line(line, 6000.0)
        self.assertIn("F6000.0", out)
        self.assertNotIn("F12000", out)
        self.assertIn("; move", out)

        line_no_f = "G1 X100 Y50 E1.2 ; comment\n"
        out_no_f = set_feedrate_on_line(line_no_f, 4500.0)
        self.assertIn("F4500.0", out_no_f)
        self.assertIn("; comment", out_no_f)

    def test_gaussian_kernel_properties(self):
        kernel, total = generate_gaussian_kernel(window_size=11, radius=2.0)
        self.assertEqual(len(kernel), 11)
        for i in range(5):
            self.assertAlmostEqual(kernel[i], kernel[10 - i], places=6)
        self.assertGreater(total, 0.95)

    def test_apply_gaussian_smoothing(self):
        speeds = [12000.0] * 10
        speeds[5] = 3000.0
        smoothed, steps = apply_gaussian_smoothing(
            speeds,
            skip_layers=1,
            window_size=11,
            radius=2.0,
            stop_threshold_mm_min=300.0,
            max_steps=1000,
        )
        self.assertGreater(steps, 0)
        for i in range(len(speeds)):
            self.assertLessEqual(smoothed[i], speeds[i] + 1e-6)
        self.assertLess(smoothed[4], 8000.0)
        self.assertLess(smoothed[6], 8000.0)
        max_adj_diff = max(abs(smoothed[i+1] - smoothed[i]) for i in range(1, len(speeds)-1))
        self.assertLessEqual(max_adj_diff, 300.0 + 1e-4)

    def test_simple_mode(self):
        lines = generate_synthetic_gcode(num_layers=12, slow_layer_idx=6, slow_speed=3000.0)
        cfg = {"mode": "simple"}
        output_lines, stats = smooth_gcode_lines(lines, cfg)
        self.assertEqual(stats["mode"], "simple")
        self.assertEqual(stats["algorithm"], "gaussian")
        self.assertGreater(stats["smoothed_layers"], 0)
        self.assertGreater(stats["steps_converged"], 0)

    def test_advanced_mode_gradient(self):
        lines = generate_synthetic_gcode(num_layers=10, slow_layer_idx=5, slow_speed=3000.0)
        cfg = {
            "mode": "advanced",
            "smoothing_algorithm": "gradient",
            "max_speed_change_per_mm": 50.0,
            "min_outer_wall_speed_mm_s": 10.0,
            "skip_first_layers": 1,
        }
        output_lines, stats = smooth_gcode_lines(lines, cfg)
        self.assertEqual(stats["mode"], "advanced")
        self.assertEqual(stats["algorithm"], "gradient")
        self.assertEqual(stats["total_layers"], 10)
        self.assertGreater(stats["smoothed_layers"], 0)

    def test_advanced_mode_custom_gaussian(self):
        lines = generate_synthetic_gcode(num_layers=10, slow_layer_idx=5, slow_speed=3000.0)
        cfg = {
            "mode": "advanced",
            "smoothing_algorithm": "gaussian",
            "gaussian_radius": 3.0,
            "gaussian_window_size": 15,
            "gaussian_stop_threshold_mm_s": 3.0,
        }
        output_lines, stats = smooth_gcode_lines(lines, cfg)
        self.assertEqual(stats["mode"], "advanced")
        self.assertEqual(stats["algorithm"], "gaussian")
        self.assertGreater(stats["smoothed_layers"], 0)

    def test_skip_first_layer(self):
        lines = generate_synthetic_gcode(num_layers=6, slow_layer_idx=1, slow_speed=3000.0)
        cfg = {"mode": "simple"}
        output_lines, stats = smooth_gcode_lines(lines, cfg)

        current_layer = -1
        in_outer = False
        layer_0_speed = None
        for line in output_lines:
            if ";LAYER_CHANGE" in line:
                current_layer += 1
                continue
            if current_layer == 0 and ";TYPE:Outer wall" in line:
                in_outer = True
                continue
            if in_outer and current_layer == 0 and "G1" in line:
                f_val = parse_feedrate(line)
                if f_val:
                    layer_0_speed = f_val
                    break

        self.assertEqual(layer_0_speed, 12000.0)

    def test_bambu_flavor_markers_parsed(self):
        """Bambu flavour exports use '; layer num/...' and '; FEATURE:' comments."""
        lines = generate_synthetic_bambu_gcode(num_layers=10, slow_layer_idx=5, slow_speed=3000.0)
        output_lines, stats = smooth_gcode_lines(lines, {"mode": "simple"})
        self.assertEqual(stats["total_layers"], 10)
        self.assertIsNone(stats["skipped_reason"])
        self.assertGreater(stats["updated_moves"], 0)

        # Only outer/overhang features may change; infill keeps its feedrate.
        output = "".join(output_lines)
        self.assertIn("G1 X12 Y12 E0.4 F18000\n", output)
        self.assertIn("G1 X10 Y10 E0.5 F15000\n", output)

    def test_bambu_flavor_outer_arc_rewritten(self):
        """Arc segments in the outer wall carry a feedrate too and must follow."""
        lines = generate_synthetic_bambu_gcode(num_layers=10, slow_layer_idx=5, slow_speed=3000.0)
        arc_index = next(i for i, line in enumerate(lines) if line.startswith("G2 "))
        self.assertRegex(lines[arc_index], r"F[0-9.]+")
        output_lines, stats = smooth_gcode_lines(lines, {"mode": "simple"})
        self.assertGreater(stats["updated_moves"], 0)
        self.assertNotEqual(output_lines[arc_index], lines[arc_index])

    def test_overhang_slowdown_does_not_drag_layers_down(self):
        """A slow overhang move must not clamp layers whose outer wall is fast.

        Bambu/Creality seed with the node maximum and never fold overhang
        speeds into that seed (SmoothCalculator::build_node).
        """
        lines = ["; HEADER_START\n"]
        for l_idx in range(6):
            lines.append(f"; layer num/total_layer_count: {l_idx + 1}/6\n")
            lines.append(f"G1 Z{(l_idx + 1) * 0.2:.2f} F6000\n")
            lines.append("; FEATURE: Outer wall\n")
            lines.append("G1 X10 Y10 E0.5 F30000\n")
            lines.append("G1 X20 Y10 E0.5\n")
            if l_idx == 3:
                lines.append("; FEATURE: Overhang wall\n")
                lines.append("G1 X25 Y20 E0.3 F600\n")

        output_lines, stats = smooth_gcode_lines(lines, {"mode": "simple"})
        self.assertEqual(stats["updated_moves"], 0)
        self.assertEqual("".join(output_lines), "".join(lines))

    def test_internal_wall_smoothing_opt_in(self):
        """Inner walls are only touched when smooth_internal_walls is on.

        The inner series runs separately: the fast inner moves get clamped to
        their own smoothed target and the slow one is never raised.
        """
        lines = generate_inner_dip_gcode()

        # Default (off): file must come out untouched.
        out_off, _ = smooth_gcode_lines(list(lines), {"mode": "simple"})
        self.assertEqual("".join(out_off), "".join(lines))

        # Opt-in: inner moves follow the inner series, outer stays flat.
        out_on, stats = smooth_gcode_lines(
            list(lines), {"mode": "simple", "smooth_internal_walls": True}
        )
        self.assertGreater(stats["updated_moves"], 0)
        changed = [i for i, (a, b) in enumerate(zip(lines, out_on)) if a != b]
        self.assertTrue(changed)
        for i in changed:
            self.assertNotIn("TYPE:", lines[i])
        # Slow inner layer is never raised above its own speed.
        self.assertIn("F3000.0\n", "".join(out_on))
        # A fast neighbour of the dip was clamped (layer 3 inner move).
        layer_inner_move = 1 + 3 * 6 + 3
        self.assertIn("TYPE:Inner wall", lines[layer_inner_move - 1])
        self.assertNotEqual(out_on[layer_inner_move], lines[layer_inner_move])

    def test_outer_wall_toggle(self):
        """Outer smoothing can run alone, or be switched off entirely."""
        lines = generate_inner_dip_gcode()

        # Both wall toggles off: nothing to do.
        out, stats = smooth_gcode_lines(
            list(lines), {"mode": "simple", "smooth_outer_walls": False}
        )
        self.assertEqual(stats["skipped_reason"], "no_walls_selected")
        self.assertEqual("".join(out), "".join(lines))

        # Outer off, inner on: only inner moves change.
        out2, stats2 = smooth_gcode_lines(
            list(lines),
            {"mode": "simple", "smooth_outer_walls": False, "smooth_internal_walls": True},
        )
        self.assertGreater(stats2["updated_moves"], 0)
        outer_moves = [line for line in out2 if "E0.5 F12000" in line]
        self.assertEqual(len(outer_moves), 8)
        changed = [i for i, (a, b) in enumerate(zip(lines, out2)) if a != b]
        self.assertTrue(all("TYPE:Inner wall" in lines[i - 1] for i in changed))

    def test_spiral_vase_skipped(self):
        lines = generate_synthetic_gcode(num_layers=10, spiral_vase=True)
        _, stats = smooth_gcode_lines(lines)
        self.assertEqual(stats["skipped_reason"], "spiral_vase_mode")
        self.assertEqual(stats["updated_moves"], 0)

    def test_non_outer_walls_preserved(self):
        lines = generate_synthetic_gcode(num_layers=6, slow_layer_idx=3, slow_speed=2000.0)
        output_lines, _ = smooth_gcode_lines(lines)

        inner_wall_f = None
        infill_f = None
        for line in output_lines:
            if "E0.5 F15000" in line:
                inner_wall_f = 15000
            if "E0.4 F18000" in line:
                infill_f = 18000

        self.assertEqual(inner_wall_f, 15000)
        self.assertEqual(infill_f, 18000)

    def test_smooth_gcode_file_end_to_end(self):
        lines = generate_synthetic_gcode(num_layers=8, slow_layer_idx=4, slow_speed=3000.0)
        with tempfile.NamedTemporaryFile("w", delete=False, suffix=".gcode", encoding="utf-8") as f:
            f.writelines(lines)
            temp_in = f.name

        temp_out = temp_in + ".out.gcode"
        try:
            stats = smooth_gcode_file(temp_in, temp_out)
            self.assertEqual(stats["total_layers"], 8)
            self.assertGreater(stats["updated_moves"], 0)
            self.assertTrue(os.path.exists(temp_out))
            with open(temp_out, "r", encoding="utf-8") as f_out:
                out_content = f_out.read()
            self.assertIn(";TYPE:Outer wall", out_content)
        finally:
            if os.path.exists(temp_in):
                os.remove(temp_in)
            if os.path.exists(temp_out):
                os.remove(temp_out)

    def test_config_load_and_save(self):
        cfg = load_config()
        self.assertIn("mode", cfg)
        self.assertIn("gaussian_radius", cfg)
        
        ok, msg = save_config({"gaussian_radius": 2.5, "mode": "advanced"})
        self.assertTrue(ok)
        reloaded = load_config()
        self.assertEqual(reloaded["gaussian_radius"], 2.5)
        self.assertEqual(reloaded["mode"], "advanced")

        # Restore default
        save_config(DEFAULT_CONFIG)
        restored = load_config()
        self.assertEqual(restored["mode"], "simple")

