    def test_capability_config_store_roundtrip(self):
        class FakeCapability:
            def __init__(self):
                self.saved = None

            def get_config(self):
                return self.saved

            def save_config(self, payload):
                self.saved = payload
                return True

        fake = FakeCapability()
        self.assertFalse(store_capability_config({"mode": "advanced"}))
        self.assertEqual(merged_capability_config(dict(DEFAULT_CONFIG))["mode"], "simple")

        set_pipeline_capability(fake)
        try:
            self.assertTrue(store_capability_config({"mode": "advanced", "gaussian_radius": 3.0}))
            merged = merged_capability_config(dict(DEFAULT_CONFIG))
            self.assertEqual(merged["mode"], "advanced")
            self.assertEqual(merged["gaussian_radius"], 3.0)
            self.assertEqual(merged["enabled"], DEFAULT_CONFIG["enabled"])
        finally:
            set_pipeline_capability(None)


